#!/usr/bin/env python3
"""Hydrate and verify the SHA-pinned official Vita02A LinkerHand asset.

The source under Vbot-lab/vita02a is copied without semantic changes. Only
URDF ``package://vita02a/meshes`` references are rewritten to local relative
paths so ROS package registration is not required. The deterministic 30-DoF
control view is then generated by the companion derivation script.
"""

from __future__ import annotations
import argparse
import hashlib
import json
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ETree
from pathlib import Path

ASSET_RELATIVE_ROOT = Path("assets/robots/vbot/Vita02A/official_meshcoll_v2")
SOURCE_RELATIVE_ROOT = Path("vita02a")
PACKAGE_PREFIX = "package://vita02a/meshes/"
RELATIVE_PREFIX = "../meshes/"

SOURCE_INPUT_SHA256 = {
    "urdf/vita02a_linkerhand_meshcoll.urdf": (
        "dda55d765cfb0114054b9ffc3fb6c75aaefefec68149f3a50f69b0279d8870eb"
    ),
    "urdf/vita02a_meshcoll.urdf": (
        "f10706dc375f8f93b017b87ea7298bad2d9f57f2662764d87fc13c2b00fa17bd"
    ),
    "vita02a_linkerhand_meshcoll.xml": (
        "7ea5c4e0990cc74db9c99e587c7b89fdf34d18d10d100032137ca819a0285518"
    ),
    "scene_linkerhand_meshcoll.xml": (
        "fcda64d4e470367d58e5a5053fa0ac0ccb0d4cc87780ed46aa419271dc949d0e"
    ),
}
HYDRATED_SOURCE_SHA256 = {
    "urdf/vita02a_linkerhand_meshcoll.urdf": (
        "a8798d82bc1d94a16fae9092c42e30ebe9d98e2dd014fb7fd5acf8aefb010f25"
    ),
    "urdf/vita02a_meshcoll.urdf": (
        "f225f369f4722105e7ae93440e861b305ea9b8dc29a60f91dd3d4ae27f4f6301"
    ),
    "vita02a_linkerhand_meshcoll.xml": SOURCE_INPUT_SHA256[
        "vita02a_linkerhand_meshcoll.xml"
    ],
    "scene_linkerhand_meshcoll.xml": SOURCE_INPUT_SHA256[
        "scene_linkerhand_meshcoll.xml"
    ],
}
DERIVED_SHA256 = {
    "urdf/vita02a_linkerhand_meshcoll_30dof.urdf": (
        "35b35a3d9a56c361fb2ebc384c9e5a69de59a94ee762aae83afcfa69de3e33f8"
    ),
    "vita02a_linkerhand_meshcoll_30dof.xml": (
        "2aef63d3e289f6c885e3970220a6d6dd4ac35746ef02645f5ff892e7941b7a11"
    ),
    "scene_linkerhand_meshcoll_30dof.xml": (
        "b239274736f65d7c517d59b30d17de6bb0dd4b7aee66c72858d6edcea5a78957"
    ),
}
MESH_FILES = 93
MESH_BYTES = 75_912_212
MESH_TREE_SHA256 = (
    "340c7205b2fc923d674d24975ebc73193b262d08d8acb42a6b2c147312e3f7e0"
)


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _mesh_tree(root: Path) -> tuple[int, int, str]:
    paths = sorted(path for path in root.rglob("*") if path.is_file())
    digest = hashlib.sha256()
    size = 0
    for path in paths:
        relative = path.relative_to(root).as_posix()
        digest.update(relative.encode())
        digest.update(b"\0")
        digest.update(bytes.fromhex(_sha256(path)))
        size += path.stat().st_size
    return len(paths), size, digest.hexdigest()


def _verify_hashes(root: Path, expected: dict[str, str], label: str) -> None:
    for relative, digest in expected.items():
        path = root / relative
        if not path.is_file():
            raise FileNotFoundError(f"Missing Vita02A {label} file: {path}")
        actual = _sha256(path)
        if actual != digest:
            raise ValueError(
                f"Vita02A {label} digest mismatch for {path}: "
                f"expected {digest}, got {actual}"
            )


def _verify_meshes(root: Path) -> dict[str, object]:
    files, size, digest = _mesh_tree(root / "meshes")
    if (files, size, digest) != (
        MESH_FILES,
        MESH_BYTES,
        MESH_TREE_SHA256,
    ):
        raise ValueError(
            "Vita02A mesh tree mismatch: expected "
            f"{MESH_FILES} files/{MESH_BYTES} bytes/{MESH_TREE_SHA256}, "
            f"got {files} files/{size} bytes/{digest}"
        )
    return {"files": files, "bytes": size, "tree_sha256": digest}


def _verify_resolved_urdf_meshes(target: Path) -> None:
    for name in (
        "vita02a_linkerhand_meshcoll.urdf",
        "vita02a_meshcoll.urdf",
        "vita02a_linkerhand_meshcoll_30dof.urdf",
    ):
        path = target / "urdf" / name
        root = ETree.parse(path).getroot()
        references = [mesh.get("filename") for mesh in root.findall(".//mesh")]
        if not references or any(
            reference is None or reference.startswith("package://")
            for reference in references
        ):
            raise ValueError(f"Unresolved mesh reference remains in {path}")
        for reference in references:
            assert reference is not None
            if not (path.parent / reference).resolve().is_file():
                raise FileNotFoundError(
                    f"Missing URDF mesh {reference!r} referenced by {path}"
                )


def _verify_target(target: Path) -> dict[str, object]:
    _verify_hashes(target, HYDRATED_SOURCE_SHA256, "resolved source")
    _verify_hashes(target, DERIVED_SHA256, "derived")
    meshes = _verify_meshes(target)
    _verify_resolved_urdf_meshes(target)
    return {
        "asset_variant": "official_meshcoll_v2_linkerhand_shoes",
        "redistribution_status": "not_verified",
        "source_identity": {
            "files_sha256": HYDRATED_SOURCE_SHA256,
            "meshes": meshes,
        },
        "derived_control_view": {
            "policy_dof_count": 30,
            "body_wrist_dof_count": 28,
            "head_dof_count": 2,
            "fixed_finger_dof_count": 22,
            "files_sha256": DERIVED_SHA256,
        },
    }


def _rewrite_urdf_mesh_paths(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    count = text.count(PACKAGE_PREFIX)
    if count == 0:
        raise ValueError(f"No Vita02A package mesh paths found in {path}")
    path.write_text(
        text.replace(PACKAGE_PREFIX, RELATIVE_PREFIX), encoding="utf-8"
    )


def _hydrate(repo_root: Path, vbot_lab: Path, *, force: bool) -> Path:
    source = vbot_lab.resolve() / SOURCE_RELATIVE_ROOT
    _verify_hashes(source, SOURCE_INPUT_SHA256, "official input")
    _verify_meshes(source)
    target = repo_root / ASSET_RELATIVE_ROOT
    if target.exists():
        if not force:
            raise FileExistsError(
                f"Vita02A target exists: {target}; use --verify-only or "
                "--force after reviewing the exact target"
            )
        shutil.rmtree(target)
    (target / "urdf").mkdir(parents=True)
    shutil.copytree(source / "meshes", target / "meshes")
    for relative in SOURCE_INPUT_SHA256:
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source / relative, destination)
    for name in (
        "vita02a_linkerhand_meshcoll.urdf",
        "vita02a_meshcoll.urdf",
    ):
        _rewrite_urdf_mesh_paths(target / "urdf" / name)

    derive_script = (
        repo_root
        / "holomotion/scripts/assets/derive_vita02a_linkerhand_30dof.py"
    )
    subprocess.run(
        [sys.executable, str(derive_script), "--repo-root", str(repo_root)],
        cwd=repo_root,
        check=True,
    )
    return target


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repo-root", type=Path, default=Path.cwd())
    parser.add_argument("--vbot-lab", type=Path)
    parser.add_argument("--verify-only", action="store_true")
    parser.add_argument("--force", action="store_true")
    args = parser.parse_args()

    repo_root = args.repo_root.resolve()
    target = repo_root / ASSET_RELATIVE_ROOT
    if not args.verify_only:
        if args.vbot_lab is None:
            parser.error("hydration requires --vbot-lab")
        target = _hydrate(repo_root, args.vbot_lab, force=args.force)

    receipt = _verify_target(target)
    receipt_path = target / "ASSET_HYDRATION_RECEIPT.json"
    if args.verify_only:
        if not receipt_path.is_file():
            raise FileNotFoundError(
                f"Missing Vita02A hydration receipt: {receipt_path}"
            )
        recorded = json.loads(receipt_path.read_text(encoding="utf-8"))
        if recorded != receipt:
            raise ValueError("Vita02A hydration receipt does not match assets")
    else:
        receipt_path.write_text(
            json.dumps(receipt, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    print(json.dumps(receipt, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
